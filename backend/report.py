"""Exportable analysis report (Markdown or self-contained HTML)."""
import html

STATUS_TEXT = {
    "answered": "Answered",
    "excerpts_only": "Relevant excerpts only",
    "insufficient_evidence": "Insufficient evidence in the paper",
}


def _md_items(section):
    if not section["items"]:
        return ["_Not found in the paper._", ""]
    out = [f"- {i['text']} _(p. {i['page']}, {i['section']})_" for i in section["items"]]
    return out + [""]


def build_markdown(paper, history):
    a = paper["analysis"]
    lines = [f"# PaperMind AI report: {paper['title'] or paper['filename']}", "",
             f"*File:* {paper['filename']}  \n*Pages:* {paper['n_pages']}  \n"
             f"*Generated:* {paper['created_at']}", ""]
    lines += ["> All statements below are extracted verbatim from the paper, with page "
              "references. Nothing is generated by a language model.", ""]
    if a.get("abstract"):
        lines += ["## Abstract", "", a["abstract"], ""]
    lines += ["## Structured summary", ""]
    for s in a.get("summary", []):
        lines += [f"### {s['label']}", ""] + _md_items(s)
    lines += ["## Key information", ""]
    for s in a.get("key_info", []):
        lines += [f"### {s['label']}", ""] + _md_items(s)
    lines += ["## Question & answer log", ""]
    if not history:
        lines += ["_No questions asked yet._", ""]
    for h in history:
        lines += [f"**Q: {h['question']}**", "",
                  f"*Status:* {STATUS_TEXT.get(h['status'], h['status'])}", ""]
        if h.get("answer"):
            lines += [f"**Answer:** {h['answer']}", ""]
        if h.get("answer_sentence"):
            lines += [f"> {h['answer_sentence']}", ""]
        for e in h.get("evidence", [])[:3]:
            lines.append(f"- _p. {e['page']} ({e['section']}, similarity {e['score']:.2f})_: "
                         f"{e['text'][:400]}{'…' if len(e['text']) > 400 else ''}")
        lines.append("")
    return "\n".join(lines)


def build_html(paper, history):
    """Tiny markdown->HTML (headings, bullets, paragraphs) with everything escaped."""
    md = build_markdown(paper, history)
    body, in_list = [], False
    for raw in md.split("\n"):
        line = html.escape(raw.rstrip())
        line = line.replace("**", "\x00")
        parts = line.split("\x00")
        line = "".join(f"<b>{p}</b>" if i % 2 else p for i, p in enumerate(parts))
        if raw.startswith("- "):
            if not in_list:
                body.append("<ul>")
                in_list = True
            body.append(f"<li>{line[2:]}</li>")
            continue
        if in_list:
            body.append("</ul>")
            in_list = False
        if raw.startswith("### "):
            body.append(f"<h3>{line[4:]}</h3>")
        elif raw.startswith("## "):
            body.append(f"<h2>{line[3:]}</h2>")
        elif raw.startswith("# "):
            body.append(f"<h1>{line[2:]}</h1>")
        elif raw.startswith("&gt; ") or raw.startswith("> "):
            body.append(f"<blockquote>{line[5:]}</blockquote>")
        elif raw.strip():
            body.append(f"<p>{line}</p>")
    if in_list:
        body.append("</ul>")
    style = ("body{font-family:system-ui,sans-serif;max-width:800px;margin:2rem auto;"
             "padding:0 1rem;line-height:1.55;color:#1c1c1e}blockquote{border-left:3px solid #999;"
             "margin:.5rem 0;padding-left:1rem;color:#444}h1{font-size:1.6rem}")
    return f"<!doctype html><meta charset='utf-8'><title>PaperMind report</title><style>{style}</style>" + "\n".join(body)
